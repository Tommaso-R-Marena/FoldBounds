"""Summarise results/*.csv into results/SUMMARY.md. stdlib only."""
import csv, glob, statistics as st, sys
from collections import defaultdict

R = []
for fn in sorted(glob.glob("experiments/coupled/results/oracle_n*.csv")):
    R += list(csv.DictReader(open(fn)))
out = []
P = out.append
fl = float
P("# Results summary (auto-generated by summarize.py)\n")
bad = [r for r in R if not (r["sound_triv"] == r["sound_sep"] == r["sound_coup"] == "1")]
chk = [r for r in R if r["checker"] != ""]
P(f"Oracle rows: {len(R)}; soundness failures (exact outside any interval): **{len(bad)}**; "
  f"checker-verified certificates: {len(chk)}, rejected: **{sum(r['checker'] != '1' for r in chk)}**.\n")

# --- widths at matched final frontier of each (n,seq,i,q,config), and at fixed budgets
def last_rows(cfg_filter=lambda c: True, upto=None):
    d = {}
    for r in R:
        if not cfg_filter(r["config"]):
            continue
        if upto is not None and int(r["regions"]) > upto:
            continue
        k = (r["n"], r["seq"], r["i"], r["q"], r["config"])
        if k not in d or int(r["regions"]) >= int(d[k]["regions"]):
            d[k] = r
    return d

P("## Median width ratios at matched frontiers (nontrivial = trivial width > 0)\n")
P("| n | config | budget<= | rows | med coupled w | med separate w | med trivial w | med coup/sep | med coup/triv | frac rows coup<triv(1e-9) |")
P("|---|---|---|---|---|---|---|---|---|---|")
for n in ("10", "12", "14"):
    for cfg in ("linear-span", "linear-ratio", "centred-ratio"):
        for budget in (100, 1000, 3000):
            d = {k: r for k, r in last_rows(lambda c: c == cfg, budget).items() if k[0] == n and fl(r["triv_w"]) > 0}
            if not d:
                continue
            v = list(d.values())
            P(f"| {n} | {cfg} | {budget} | {len(v)} | {st.median(fl(r['coup_w']) for r in v):.3f} | "
              f"{st.median(fl(r['sep_w']) for r in v):.3f} | {st.median(fl(r['triv_w']) for r in v):.3f} | "
              f"{st.median(fl(r['coup_w']) / fl(r['sep_w']) for r in v):.3f} | "
              f"{st.median(fl(r['coup_w']) / fl(r['triv_w']) for r in v):.3f} | "
              f"{sum(fl(r['coup_w']) < fl(r['triv_w']) - 1e-9 for r in v) / len(v):.2f} |")

# --- by q and by mutation type at budget<=1000 (best config per n by median)
P("\n## By q (linear-span, budget<=1000, nontrivial rows)\n")
P("| n | q | rows | med coup w | med sep w | med triv w | med coup/triv |")
P("|---|---|---|---|---|---|---|")
d = last_rows(lambda c: c == "linear-span", 1000)
for n in ("10", "12", "14"):
    for q in ("3/2", "2", "3"):
        v = [r for k, r in d.items() if k[0] == n and k[3] == q and fl(r["triv_w"]) > 0]
        if v:
            P(f"| {n} | {q} | {len(v)} | {st.median(fl(r['coup_w']) for r in v):.3f} | {st.median(fl(r['sep_w']) for r in v):.3f} | "
              f"{st.median(fl(r['triv_w']) for r in v):.3f} | {st.median(fl(r['coup_w']) / fl(r['triv_w']) for r in v):.3f} |")

# --- exploration fractions: first checkpoint whose width <= target (same config)
def exploration(rows_all, title, ns, cfgs):
    P(title)
    P("Within each (n,seq,i,q,config) refinement path (path ends at the budget cap => censored). Only rows whose trivial width exceeds the target.\n")
    P("| n | config | target kT | rows | coupled reached | separate reached | med frac coupled (reached) | med frac separate (reached) | med regions coupled | med regions separate | max regions on path |")
    P("|---|---|---|---|---|---|---|---|---|---|---|")
    paths = defaultdict(list)
    for r in rows_all:
        if r["config"] != "bfs":
            paths[(r["n"], r["seq"], r["i"], r["q"], r["config"])].append(r)
    for n in ns:
        for cfg in cfgs:
            for tgt in (0.5, 0.1):
                rows = 0; rc = []; rs = []; kc = []; ks = []; mx = 0
                for k, v in paths.items():
                    if k[0] != n or k[4] != cfg or fl(v[0]["triv_w"]) <= tgt:
                        continue
                    rows += 1
                    v = sorted(v, key=lambda r: int(r["regions"]))
                    mx = max(mx, int(v[-1]["regions"]))
                    a = next((r for r in v if fl(r["coup_w"]) <= tgt), None)
                    b = next((r for r in v if fl(r["sep_w"]) <= tgt), None)
                    if a: rc.append(fl(a["trie_frac"])); kc.append(int(a["regions"]))
                    if b: rs.append(fl(b["trie_frac"])); ks.append(int(b["regions"]))
                if rows:
                    m = lambda x: f"{st.median(x):.3f}" if x else "n/a"
                    P(f"| {n} | {cfg} | {tgt} | {rows} | {len(rc)} | {len(rs)} | {m(rc)} | {m(rs)} | {m(kc)} | {m(ks)} | {mx} |")
    P("")

exploration(R, "\n## Exploration fraction to reach a width target (trie nodes / all prefix nodes)\n",
            ("10", "12", "14"), ("linear-span", "linear-ratio", "centred-ratio"))
D = []
for fn in sorted(glob.glob("experiments/coupled/results/deep_n*.csv")):
    D += list(csv.DictReader(open(fn)))
if D:
    badD = [r for r in D if not (r["sound_triv"] == r["sound_sep"] == r["sound_coup"] == "1")]
    exploration(D, f"## Deep n=12 run (cap 20000 regions = 67% of the 30073 leaves; 2 sequences; soundness failures: {len(badD)})\n",
                ("12",), ("linear-span", "centred-ratio"))

# --- exactness check of bounds containing exact, and example of tightest coupled widths
P("\n## BFS-depth frontiers (uniform prefix depth), n=12, median over nontrivial rows\n")
P("| depth m | regions(med) | coupled w | separate w | trivial w |")
P("|---|---|---|---|---|")
by = defaultdict(list)
for r in R:
    if r["config"] == "bfs" and r["n"] == "12" and fl(r["triv_w"]) > 0:
        by[int(r["regions"]) if False else r["regions"]].append(r)
for k in sorted(by, key=int):
    v = by[k]
    P(f"| ({k} regions) | {k} | {st.median(fl(r['coup_w']) for r in v):.3f} | {st.median(fl(r['sep_w']) for r in v):.3f} | {st.median(fl(r['triv_w']) for r in v):.3f} |")

# --- large n
L = []
for fn in sorted(glob.glob("experiments/coupled/results/large_n*.csv")):
    L += list(csv.DictReader(open(fn)))
if L:
    P("\n## n=30 and n=50 (no oracle; all certificates machine-checked)\n")
    P(f"Rows: {len(L)}; checker rejections: **{sum(r['checker'] != '1' for r in L)}**; coupled not inside trivial: **{sum(r['coup_in_triv'] != '1' for r in L)}**.\n")
    P("| n | config | regions | rows | med coupled w | med separate w | med trivial w | med coup/triv | med cert KB |")
    P("|---|---|---|---|---|---|---|---|---|")
    g = defaultdict(list)
    for r in L:
        g[(r["n"], r["config"], str(min((100, 500, 1500), key=lambda b: abs(b - int(r["regions"])))))].append(r)
    for k in sorted(g, key=lambda k: (int(k[0]), k[1], int(k[2]))):
        v = g[k]
        P(f"| {k[0]} | {k[1]} | {k[2]} | {len(v)} | {st.median(fl(r['coup_w']) for r in v):.3f} | {st.median(fl(r['sep_w']) for r in v):.3f} | "
          f"{st.median(fl(r['triv_w']) for r in v):.3f} | {st.median(fl(r['coup_w']) / fl(r['triv_w']) for r in v if fl(r['triv_w']) > 0):.3f} | "
          f"{st.median(int(r['cert_bytes']) for r in v) / 1000:.0f} |")
open("experiments/coupled/results/SUMMARY.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
